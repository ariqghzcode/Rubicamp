let warna = "kuning";
// Tulis kode switch statement di sini
switch (warna) {
    case "merah":
        console.log("Lampu " + warna + ": Berhenti, ")
        break;
     case "kuning":
        console.log("Lampu " + warna + ": Hati-hati, bersiap berhenti")
        break;
    case "hijau":
        console.log("Lampu " + warna + ": Jalan, ")
        break;

    default:
        console.log("Lampu Rusak")
        break;
}