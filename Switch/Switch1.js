let nomorHari = 3;
let Hari;
// Tulis kode switch statement di sini
switch (nomorHari){
    case 1:
        Hari = "Senin"
        break;
    case 2: 
        Hari = "Selasa"   
        break;
    case 3: 
        Hari = "Rabu"
        break;   
    case 4:    
        Hari = "Kamis"
        break;
    case 5:    
        Hari = "Jum'at"
        break;
    case 6:
        Hari = "Sabtu"
        break;
    case 7:    
        Hari = "Ahad"
        break;

}
console.log("Hari ke-" + nomorHari + ": " + Hari)