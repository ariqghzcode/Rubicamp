let angka1 = 10;
let angka2 = 3;
let operator = "/";
// Tulis kode if-else if-else statement di sini
if (operator == "+") {
    console.log (angka1 + operator + angka2 + " = " + (angka1 + angka2));
    
} else if (operator == "-") {
    console.log (angka1 + operator + angka2 + " = " + (angka1 - angka2));
    
} else if (operator == "*") {
    console.log (angka1 + operator + angka2 + " = " + (angka1 * angka2));
    
} else if (operator == "/") {
    console.log (angka1 + operator + angka2 + " = " + (angka1 / angka2));
    
} else {
    console.log ("Operator tidak valid");
}